#!/usr/bin/env python3
"""IT23 P3: summarise results/sim_q5_all.tsv (stdlib only). Writes results/sim_q5_summary.md and prints it.
Closeness to the healthy attractor is not proof of functional benefit; MYELIN_OL is a scenario premise.   usage: python3 analyze_q5.py [--help]"""
import sys
if len(sys.argv) > 1 and sys.argv[1] in ("-h", "--help"):
    print(__doc__); raise SystemExit(0)
import csv, json, collections, os
HERE = os.path.dirname(os.path.abspath(__file__))
R = list(csv.DictReader(open(os.path.join(HERE, "results", "sim_q5_all.tsv")), delimiter="\t"))
PK = ("logic", "receptor_edges", "neg_feedback", "qualified_loops", "il1b_processing")
cell = {}
for r in R:
    cell[(r["scenario"], tuple(r[k] for k in PK), r["intervention"])] = json.loads(r["final_states"])
prem = sorted({tuple(r[k] for k in PK) for r in R}); scen = list(dict.fromkeys(r["scenario"] for r in R)); ivs = list(dict.fromkeys(r["intervention"] for r in R))
def out3(s): return (str(s["CYT"]), str(s["MYELIN_OL"]), str(s["GFAP"]))
def outset(L): return frozenset(out3(s) for s in L)
def fullset(L): return frozenset(json.dumps(s, sort_keys=True) for s in L)
def healthy(L): return all(out3(s) == ("0", "1", "0") for s in L)
o = []
P = o.append
P("# Q5 simulation summary (auto-generated by analyze_q5.py)\n")
P(f"{len(prem)} premise combinations x {len(scen)} scenarios x {len(ivs)} interventions = {len(R)} cells. Boolean; counts are numbers of PREMISE COMBINATIONS (out of {len(prem)}), not probabilities.\n")
P("Readouts: CYT = any of IL6/TNF/IL1B signal on; MYELIN_OL = scenario-defined outcome node (NOT a measurement); GFAP = RELA|STAT3 proxy. 'healthy-like' = CYT 0, MYELIN_OL 1, GFAP 0 in every final attractor. Closeness to a healthy attractor is not proof of functional benefit.\n")
P("## 1. Untreated disease state")
for sc in scen:
    c = collections.Counter(str(sorted(outset(cell[(sc, p, 'none')]))) for p in prem)
    P(f"- {sc}: {dict(c)}")
P("\n## 2. Interventions reaching a healthy-like final state (n of 32 premise combinations; 'none' row = spontaneous resolution)")
P("| intervention | " + " | ".join(scen) + " |"); P("|---|" + "---|" * len(scen))
for iv in ivs:
    P(f"| {iv} | " + " | ".join(str(sum(healthy(cell[(sc, p, iv)]) for p in prem)) for sc in scen) + " |")
P("\n## 3. Interventions that switch the cytokine signal off (CYT 0 in every final attractor), n of 32")
P("| intervention | " + " | ".join(scen) + " |"); P("|---|" + "---|" * len(scen))
for iv in ivs:
    P(f"| {iv} | " + " | ".join(str(sum(all(str(s['CYT']) == '0' for s in cell[(sc, p, iv)]) for p in prem)) for sc in scen) + " |")
P("\n## 4. Sign dependence of the unknown role: same intervention under damaging_mediator vs compensatory (n of 32)")
P("MYELIN_OL final value under the intervention compared with the untreated disease state in the same premise combination.\n")
P("| intervention | benefit if damaging AND harm if compensatory (sign-dependent) | benefit under both | harm under both | no change under both | other |"); P("|---|---|---|---|---|---|")
def mv(L): return {str(s["MYELIN_OL"]) for s in L}
for iv in ivs[1:]:
    c = collections.Counter()
    for p in prem:
        eff = []
        for sc in ("damaging_mediator", "compensatory"):
            base = mv(cell[(sc, p, "none")]); now = mv(cell[(sc, p, iv)])
            eff.append("up" if (now == {"1"} and base == {"0"}) else "down" if (now == {"0"} and base == {"1"}) else "same" if now == base else "mixed")
        c[tuple(eff)] += 1
    P(f"| {iv} | {c[('up','down')]} | {c[('up','up')]} | {c[('down','down')]} | {c[('same','same')]} | {sum(v for k,v in c.items() if k not in [('up','down'),('up','up'),('down','down'),('same','same')])} |")
P("\n## 5. Does the simulation separate interventions the current method treats as equivalent?")
P("Pairs: (a) BRD4i vs EP300i: both inhibit, both have a qualified positive CollecTRI edge onto TNF and IL6 seeds, both H_HARM in proposals_it21 Q5 (BRD4 43 families, EP300 2). (b) Pairs that the engine cannot rank apart because their only link is the same signed edge class: IL6neut/TNFneut/IL1Bneut (seed genes themselves; none appears as a Q5 main_target in proposals_it21), JAKi/IKKi/STAT3i (upstream signalling; none appears either). (c) pharmacological vs genetic at the same node.")
pairs = [("BRD4i", "EP300i"), ("IL6neut", "TNFneut"), ("IL6neut", "IL1Bneut"), ("TNFneut", "IL1Bneut"), ("JAKi", "STAT3i"), ("IKKi", "STAT3i"), ("JAKi", "IKKi"),
         ("IL6neut", "KD_IL6_tx"), ("TNFneut", "KD_TNF_tx"), ("IL1Bneut", "KD_IL1B_tx"), ("STAT3i", "KD_STAT3"), ("IKKi", "KD_RELA")]
P("\n| pair | scenario group | separated on outcome readouts (CYT/MYELIN/GFAP), n of 32 | separated only on full node vector (transcript/activity layers), n of 32 |"); P("|---|---|---|---|")
for a, b in pairs:
    for grp, scs in (("damaging_mediator", ["damaging_mediator"]), ("all 6 scenarios pooled", scen)):
        tot = len(prem) * len(scs)
        so = sum(outset(cell[(sc, p, a)]) != outset(cell[(sc, p, b)]) for sc in scs for p in prem)
        sf = sum(fullset(cell[(sc, p, a)]) != fullset(cell[(sc, p, b)]) and outset(cell[(sc, p, a)]) == outset(cell[(sc, p, b)]) for sc in scs for p in prem)
        P(f"| {a} vs {b} | {grp} | {so}/{tot} | {sf}/{tot} |")
P("\n## 6. BRD4i vs EP300i by logic premise (damaging_mediator)")
for lg in ("OR", "COFACTOR"):
    ps = [p for p in prem if p[0] == lg]
    so = sum(outset(cell[("damaging_mediator", p, 'BRD4i')]) != outset(cell[("damaging_mediator", p, 'EP300i')]) for p in ps)
    sf = sum(fullset(cell[("damaging_mediator", p, 'BRD4i')]) != fullset(cell[("damaging_mediator", p, 'EP300i')]) for p in ps)
    P(f"- logic={lg}: outcome-separated {so}/{len(ps)}, node-vector-separated {sf}/{len(ps)}")
P("\n## 7. Feedback scenario (transient trigger): is the disease state self-sustaining after the trigger ends?")
for p in prem:
    pass
c = collections.Counter()
for p in prem:
    s0 = outset(cell[("feedback_transient", p, "none")])
    c[("sustained" if s0 != {("0", "1", "0")} else "resolved", "receptor=" + p[1], "qualified_loops=" + p[3])] += 1
for k, v in sorted(c.items()): P(f"- {k}: {v}")
P("\n## 8. Prevention (genetic clamp from phase 1) vs reversal (drug from phase 2), feedback_transient, healthy-like counts")
for iv in ["IL6neut", "KD_IL6_tx", "IKKi", "KD_RELA", "STAT3i", "KD_STAT3"]:
    P(f"- {iv}: {sum(healthy(cell[('feedback_transient', p, iv)]) for p in prem)}/32")
open(os.path.join(HERE, "results", "sim_q5_summary.md"), "w").write("\n".join(o) + "\n")
print("\n".join(o))

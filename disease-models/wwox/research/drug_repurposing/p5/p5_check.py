#!/usr/bin/env python3
"""Offline check for the P5 tables. Run from anywhere: python3 p5_check.py
1. every cell of cells.json is a contiguous piece of the stored card's field it names (or UNKNOWN with no field);
2. no score/rank/probability/index key exists in cells.json or lookup_summary.json;
3. no dose-like quantity, e-mail string or truncated digest in any p5 file (the one coordinator-relayed, superseded
   exposure statement is exempt from the cell rule because it is labelled as NOT a card cell and carries no dose);
4. tables are regenerated byte-identically by build_p5.py."""
import json, os, re, subprocess, sys, hashlib
HERE = os.path.dirname(os.path.abspath(__file__)); DRUG = os.path.join(HERE, "..")
bad = []
def walk(d, path):
    cur = d
    for k in path.split("."):
        cur = cur[k]
    return " | ".join(map(str, cur)) if isinstance(cur, list) else str(cur)
cells = json.load(open(os.path.join(HERE, "cells.json")))
FORBID = re.compile(r"^(score|rank|ranking|probability|prob|index|priority|weight|total)$", re.I)
def keys(o):
    if isinstance(o, dict):
        for k, v in o.items():
            yield k; yield from keys(v)
    elif isinstance(o, list):
        for x in o: yield from keys(x)
for fn in ("cells.json", "lookup_summary.json"):
    for k in keys(json.load(open(os.path.join(HERE, fn)))):
        if FORBID.match(k): bad.append(f"{fn}: forbidden key {k}")
n = 0
for path in ("RECUPERO_PROFONDO", "BENEFICIO_PRECOCE"):
    for r in cells[path]:
        card = json.load(open(os.path.join(DRUG, r["card_file"])))
        for dim, c in r["dims"].items():
            if dim == "exposure_proportionality_SUPERSEDED":
                continue
            n += 1
            if c["card_field"] is None:
                if c["value"] != "UNKNOWN": bad.append(f"{r['id']} {dim}: no field but value {c['value'][:30]}")
                continue
            full = walk({"input": card["input"]}, c["card_field"])
            if c["value"] not in full: bad.append(f"{r['id']} {dim}: not a contiguous piece of {c['card_field']}")
dose = re.compile(r"\b\d+(\.\d+)?\s*(mg|mcg|µg|ug|g/kg|mg/kg|ml|mL|IU)\b")
mail = re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")
for fn in sorted(os.listdir(HERE)):
    if fn.endswith((".md", ".json", ".py")) and fn != "p5_check.py":
        t = open(os.path.join(HERE, fn)).read()
        if dose.search(t): bad.append(f"{fn}: dose-like quantity {dose.search(t).group(0)}")
        if mail.search(t): bad.append(f"{fn}: e-mail-like string")
        if re.search(r"\b[0-9a-f]{40,63}\b", t) and not re.search(r"\b[0-9a-f]{64}\b", t): bad.append(f"{fn}: truncated digest?")
before = {f: hashlib.sha256(open(os.path.join(HERE, f), "rb").read()).hexdigest() for f in ("cells.json", "tables_deep.md", "tables_early.md", "matrix.md")}
subprocess.run([sys.executable, os.path.join(HERE, "build_p5.py")], check=True, capture_output=True)
for f, h in before.items():
    if hashlib.sha256(open(os.path.join(HERE, f), "rb").read()).hexdigest() != h: bad.append(f"{f}: not reproduced by build_p5.py")
print(f"cells checked: {n}; problems: {len(bad)}")
for b in bad: print(" -", b)
sys.exit(1 if bad else 0)

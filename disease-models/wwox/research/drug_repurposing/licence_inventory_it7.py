TOP = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, cwd=os.path.dirname(os.path.abspath(__file__))).stdout.strip() or "."


def git(*args, check=True, text=True, inp=None):
    r = subprocess.run(["git", *args], capture_output=True, text=text, input=inp, cwd=TOP)
    if check and r.returncode != 0:
        sys.stderr.write(r.stderr)
        raise SystemExit(3)
    return r.stdout


def family(path):
    for n, rx, o, t, c in FAM_RX:
        if rx.search(path):
            return n
    return "other"


def cat_blobs(shas):
    """Yield (sha, bytes) for every sha through one `git cat-file --batch` process."""
    shas = list(shas)
    if not shas:
        return
    p = subprocess.Popen(["git", "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, cwd=TOP)
    import threading

    def feed():
        try:
            for s in shas:
                p.stdin.write((s + "\n").encode())
            p.stdin.close()
        except BrokenPipeError:
            pass

    t = threading.Thread(target=feed)
    t.start()
    for s in shas:
        h = p.stdout.readline().split()
        if len(h) < 3:
            yield s, b""
            continue
        sz = int(h[2])
        data = p.stdout.read(sz)
        p.stdout.read(1)
        yield s, data
    t.join()
    p.wait()


def tip_entries(rev):
    out = git("ls-tree", "-r", "-l", "-z", "--full-tree", rev)
    rows = []
    for rec in out.split("\0"):
        if not rec:
            continue
        meta, path = rec.split("\t", 1)
        mode, typ, sha, size = meta.split()
        if typ == "blob":
            rows.append((path, sha, int(size)))
    return rows


def ext(path):
    return path.rsplit(".", 1)[-1].lower() if "." in path.rsplit("/", 1)[-1] else ""


def md_table(head, rows):
    print("| " + " | ".join(head) + " |")
    print("|" + "|".join("---" for _ in head) + "|")
    for r in rows:
        print("| " + " | ".join(str(x) for x in r) + " |")
    print()


QUOTE_RX = re.compile(r"[“\"]([^“”\"\n]{40,}?)[”\"]")


def quote_stats(text):
    runs = [len(m.group(1).split()) for m in QUOTE_RX.finditer(text)]
    runs = [w for w in runs if w >= 10]
    bq = sum(1 for l in text.splitlines() if l.startswith(">"))
    return runs, bq


def section1(rev, entries):
    print("## 1. Tip by content family\n")
    print(f"Command: `git ls-tree -r -l -z {rev}`; family = first matching rule of the FAMILIES table in this script.\n")
    fam = collections.OrderedDict((n, [0, 0, 0, set()]) for n, *_ in FAMILIES)
    tab_paths = [(p, s) for p, s, z in entries if ext(p) in TABULAR or p.endswith(".jsonl.gz") or p.endswith(".tsv") or p.endswith(".csv")]
    rows_of = {}
    shas_by = collections.defaultdict(list)
    for p, s in tab_paths:
        shas_by[s].append(p)
    for sha, data in cat_blobs(list(shas_by)):
        for p in shas_by[sha]:
            d = data
            if p.endswith(".gz"):
                try:
                    d = gzip.decompress(data)
                except Exception:
                    d = b""
            n = d.count(b"\n") + (1 if d and not d.endswith(b"\n") else 0)
            if ext(p) in ("tsv", "csv"):
                n = max(n - 1, 0)
            rows_of[p] = n
    for p, s, z in entries:
        n = family(p)
        f = fam[n]
        f[0] += 1
        f[1] += z
        f[2] += rows_of.get(p, 0)
    names = {n: (o, t, c) for n, _, o, t, c in FAMILIES}
    md_table(["family", "files", "bytes", "tabular rows", "origin", "terms", "proposed class"],
             [(n, f[0], f[1], f[2], *names[n]) for n, f in fam.items() if f[0]])
    print(f"Total: {len(entries)} files, {sum(z for _, _, z in entries)} bytes.\n")
    # binaries
    print("### Binary and document files at the tip\n")
    print("Command: tip entries whose extension is in " + ", ".join(sorted(BIN_EXT)) + ".\n")
    byd = collections.Counter()
    byb = collections.Counter()
    for p, s, z in entries:
        if ext(p) in BIN_EXT:
            d = p.rsplit("/", 1)[0]
            key = (d, ext(p))
            byd[key] += 1
            byb[key] += z
    md_table(["directory", "ext", "files", "bytes"], [(d, e, byd[(d, e)], byb[(d, e)]) for d, e in sorted(byd)])
    pa = [p for p, _, _ in entries if "/page_adjudications/" in p and ext(p) in ("png", "jpg", "jpeg", "tif", "tiff")]
    print(f"Page-adjudication image files at the tip: {len(pa)}. Git-ignored since de089055; the derivation JSON is tracked.\n")
    return rows_of


def section2(rev):
    print("## 2. Third-party rows embedded in the catalogue\n")
    path = DR + "catalog/catalog.jsonl.gz"
    print(f"Command: parse `{path}` at {rev}; count `targets[]` by `claim_source` (DGIdb interaction rows) and `source` (ChEMBL curated mechanism rows). Class from `view/shareable_sources.json` `claim_source_policy`.\n")
    raw = git("cat-file", "blob", f"{rev}:{path}", text=False)
    pol = json.loads(git("cat-file", "blob", f"{rev}:{DR}view/shareable_sources.json")).get("claim_source_policy", {})
    n_rec = 0
    cnt = collections.Counter()
    origins = collections.Counter()
    recsrc = collections.Counter()
    for l in gzip.decompress(raw).decode("utf-8").splitlines():
        r = json.loads(l)
        n_rec += 1
        origins[r.get("origin")] += 1
        for s in r.get("source_records", []):
            recsrc[s.get("source")] += 1
        for t in r.get("targets", []):
            cnt[t.get("claim_source") or t.get("source")] += 1
    rows = []
    for k, v in sorted(cnt.items(), key=lambda x: (-x[1], x[0])):
        pe = pol.get(k, {})
        rows.append((k, v, pe.get("class", "ChEMBL: B (CC BY-SA 3.0)" if k == "ChEMBL curated mechanism" else "NOT IN POLICY"), (pe.get("terms") or "")[:110]))
    md_table(["claim source", "target rows", "class (policy file)", "terms as recorded"], rows)
    tot = sum(cnt.values())
    cls = collections.Counter()
    for k, v in cnt.items():
        c = pol.get(k, {}).get("class", "B" if k == "ChEMBL curated mechanism" else "?")
        cls[c] += v
    print(f"Catalogue records: {n_rec}; target rows: {tot}; by class: " + ", ".join(f"{c}={cls[c]}" for c in sorted(cls)) + ".\n")
    print("Records by origin: " + ", ".join(f"{k}={v}" for k, v in sorted(origins.items(), key=str)) + ".")
    print("Records by source_records source: " + ", ".join(f"{k}={v}" for k, v in sorted(recsrc.items(), key=str)) + ".\n")
    return pol


def section2b(rev, entries, pol):
    print("### 2b. Third-party rows outside the catalogue (tip)\n")
    names = sorted((k for k, v in pol.items() if v.get("class") in ("B", "C")), key=len, reverse=True)
    rx_tag = re.compile(r'"sources": "([^"]{1,200})"')
    rx_name = re.compile(r"\b(" + "|".join(map(re.escape, names)) + r")\b")
    print("Command: (a) in every tracked text file except the catalogue, count JSON entries of the form `\"sources\": \"<label>\"` "
          "per label (DGIdb-style row tags); (b) in the family `raw third-party responses`, count word-bounded mentions of class B/C claim-source names "
          "and files by top-level folder. Mentions are not rows.\n")
    tags = collections.Counter()
    tagfiles = collections.defaultdict(set)
    raw = collections.defaultdict(lambda: [0, 0, 0])
    sel = [(p, s) for p, s, z in entries if ext(p) in ("json", "jsonl", "tsv", "html", "md", "csv", "txt", "gz") and "catalog.jsonl" not in p]
    by = collections.defaultdict(list)
    for p, s in sel:
        by[s].append(p)
    for sha, data in cat_blobs(sorted(by)):
        for p in by[sha]:
            d = data
            if p.endswith(".gz"):
                try:
                    d = gzip.decompress(data)
                except Exception:
                    continue
            t = d.decode("utf-8", "replace")
            for m in rx_tag.finditer(t):
                for lab in m.group(1).split(";"):
                    lab = lab.strip()
                    if lab in pol or lab in ("PRISM", "Drug Repurposing Hub"):
                        tags[lab] += 1
                        tagfiles[lab].add(p)
            if family(p).startswith("raw third-party"):
                key = p.rsplit("/", 1)[0].replace(DR, "")
                r = raw[key]
                r[0] += 1
                r[1] += len(d)
                r[2] += len(rx_name.findall(t))
    md_table(["label", "tagged entries", "files"], [(k, v, len(tagfiles[k])) for k, v in sorted(tags.items(), key=lambda x: (-x[1], x[0]))])
    md_table(["raw folder", "files", "bytes (decompressed)", "mentions of class B/C source names"], [(k, *v) for k, v in sorted(raw.items())])


def section3(rev, entries):
    print("## 3. Quotation exposure in full-text-derived material\n")
    print("Command: for each tracked `.md` in the stated scope, count double-quoted runs of at least 10 words "
          "(regex `[\\u201c\"]...{40,}...[\\u201d\"]`) and blockquote lines (`>`). This is an UPPER BOUND on verbatim "
          "third-party text: it also counts the repository's own quotations of itself, of tools, and of its own records, and "
          "it misses quotation without marks. Whether a run is a quotation of a paper is not decided here.\n")
    scopes = [
        ("fulltext_dossiers/*.md", lambda p: "/fulltext_dossiers/" in p and p.endswith(".md")),
        ("page_adjudications/*.md", lambda p: "/page_adjudications/" in p and p.endswith(".md")),
        ("disease-models/wwox/analysis/*.md (excl. data/)", lambda p: p.startswith("disease-models/wwox/analysis/") and "/data/" not in p and p.endswith(".md")),
        ("disease-models/wwox/research/*.md (excl. drug_repurposing, dossiers, adjudications)", lambda p: p.startswith("disease-models/wwox/research/") and "/drug_repurposing/" not in p and "/fulltext_dossiers/" not in p and "/page_adjudications/" not in p and p.endswith(".md")),
        ("drug_repurposing/**/*.md", lambda p: p.startswith(DR) and p.endswith(".md")),
        ("learning/, reviews/ *.md", lambda p: p.startswith(("learning/", "reviews/")) and p.endswith(".md")),
    ]
    rows = []
    by_sha = {p: s for p, s, _ in entries}
    for name, fn in scopes:
        ps = sorted(p for p in by_sha if fn(p))
        runs_all = []
        bq = 0
        mx = ("", 0)
        sh = collections.defaultdict(list)
        for p in ps:
            sh[by_sha[p]].append(p)
        for sha, data in cat_blobs(list(sh)):
            runs, b = quote_stats(data.decode("utf-8", "replace"))
            for p in sh[sha]:
                runs_all += runs
                bq += b
                if runs and max(runs) > mx[1]:
                    mx = (p, max(runs))
        rows.append((name, len(ps), len(runs_all), sum(1 for w in runs_all if w >= 25), sum(1 for w in runs_all if w >= 50), mx[1], sum(runs_all), bq))
    md_table(["scope", "files", "quoted runs >=10 words", ">=25", ">=50", "longest run (words)", "words in runs", "blockquote lines"], rows)
    # manifests
    mf = sorted(p for p in by_sha if "/deepdive_manifests/" in p and p.endswith(".json"))
    words = []
    for sha, data in cat_blobs([by_sha[p] for p in mf]):
        try:
            d = json.loads(data)
        except Exception:
            continue
        v = d.get("verbatim_locators")
        ents = v.get("entries", []) if isinstance(v, dict) else []
        for e in ents:
            if isinstance(e, dict) and isinstance(e.get("snippet"), str):
                words.append(len(e["snippet"].split()))
    print(f"Deep-dive manifests: {len(mf)} files; `verbatim_locators.entries[].snippet` count {len(words)}, total words {sum(words)}, "
          f"longest {max(words) if words else 0}, snippets of >=25 words {sum(1 for w in words if w >= 25)}, >=50 words {sum(1 for w in words if w >= 50)}.\n")


def section4(rev):
    print("## 4. History: binary, document and image files ever committed\n")
    print(f"Command: `git log {rev} --diff-filter=AD --name-status --format=C%x09%H%x09%cs`, extensions in the binary set; "
          "tip status from `git ls-tree`; reachability from `git merge-base --is-ancestor`.\n")
    out = git("log", rev, "--diff-filter=AD", "--name-status", "--format=C\t%H\t%cs")
    cur = None
    adds = collections.defaultdict(list)
    dels = collections.defaultdict(list)
    for l in out.splitlines():
        if not l:
            continue
        if l.startswith("C\t"):
            _, h, d = l.split("\t")
            cur = (h, d)
            continue
        st, p = l.split("\t", 1)
        if ext(p) in BIN_EXT:
            (adds if st == "A" else dels)[p].append(cur)
    tip = {p for p, _, _ in tip_entries(rev)}
    refs = [r for r in ("origin/main", "development/main") if git("rev-parse", "--verify", "-q", r, check=False).strip()]
    rows = []
    for p in sorted(set(adds) | set(dels)):
        first = adds[p][-1] if adds[p] else (None, "")
        last_del = dels[p][0] if dels[p] else None
        reach = ",".join(r for r in refs if first[0] and subprocess.run(["git", "merge-base", "--is-ancestor", first[0], r], cwd=TOP).returncode == 0) or "none"
        rows.append((p, "yes" if p in tip else "no", first[0][:8] if first[0] else "", first[1], (last_del[0][:8] + " " + last_del[1]) if last_del else "", reach))
    # compress by directory when many
    bydir = collections.OrderedDict()
    for r in rows:
        d = r[0].rsplit("/", 1)[0]
        bydir.setdefault(d, []).append(r)
    summ = []
    for d, rs in bydir.items():
        gone = [r for r in rs if r[1] == "no"]
        summ.append((d, len(rs), len(gone), ",".join(sorted({r[2] for r in rs}))[:60], ",".join(sorted({r[4].split(' ')[0] for r in gone if r[4]}))[:40], ",".join(sorted({x for r in rs for x in r[5].split(",")}))))
    md_table(["directory", "paths ever", "not at tip", "first-add commits", "delete commits", "reachable from"], summ)
    print("Per path, only paths NOT at the tip (they are the ones history alone preserves):\n")
    md_table(["path", "first add", "date", "last delete", "reachable from"], [(r[0], r[2], r[3], r[4], r[5]) for r in rows if r[1] == "no"])


def section5(rev, pol):
    print("## 5. History: versions of files that embed third-party rows\n")
    watched = [DR + "catalog/catalog.jsonl.gz", DR + "view/index.html", DR + "view/index_shareable.html",
               DR + "view/shareable_package/index.html", DR + "join/evidence.json", DR + "join/cards.json", DR + "coverage/associations.jsonl.gz",
               DR + "catalog/ligand_reconciliation.tsv", DR + "gse156243/kg_lookup/WWOX.txt", DR + "clinical_census_20261020_raw/WWOX_page1.json.gz"]
    names = [k for k, v in pol.items() if v.get("class") == "C"]
    rx = re.compile(r"\b(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")\b") if names else None
    print("Command: `git log REV --format=%H%x09%cs -- <path>` per file; distinct blob versions; `mentions` = word-bounded occurrences of a class-C claim-source name "
          "(" + ", ".join(sorted(names)) + ") in the decompressed blob. A mention is an indicator, not a row count (the catalogue's rows are counted in section 2).\n")
    rows = []
    for p in watched:
        log = git("log", rev, "--format=%H\t%cs", "--", p).splitlines()
        if not log:
            rows.append((p, 0, "", "", "", ""))
            continue
        blobs = collections.OrderedDict()
        for l in log:
            h, d = l.split("\t")
            sha = git("rev-parse", f"{h}:{p}", check=False).strip()
            if sha:
                blobs.setdefault(sha, (h, d))
        ms = []
        for sha, data in cat_blobs(list(blobs)):
            if p.endswith(".gz"):
                try:
                    data = gzip.decompress(data)
                except Exception:
                    pass
            ms.append(len(rx.findall(data.decode("utf-8", "replace"))) if rx else 0)
        first = log[-1].split("\t")
        rows.append((p.replace(DR, ""), len(log), len(blobs), f"{first[0][:8]} {first[1]}", min(ms) if ms else "", max(ms) if ms else ""))
    md_table(["path (relative to drug_repurposing/)", "commits touching", "distinct blobs", "first commit", "min mentions", "max mentions"], rows)


def section6(rev):
    print("## 6. History: identities in commit metadata\n")
    print(f"Command: `git log {rev} --format=%an|%ae|%cn|%ce`; each address is classified and shown only as an 8-hex SHA-256 digest "
          "(no address is printed). Categories: noreply (users.noreply.github.com), vendor (anthropic.com), placeholder "
          "(example.*, .invalid), host-bound (an operator machine hostname), personal-mailbox (public webmail domains), other.\n")
    out = git("log", rev, "--format=%ae%x09%ce")
    cnt = collections.Counter()
    for l in out.splitlines():
        for e in l.split("\t"):
            e = e.strip().lower()
            if not e:
                continue
            dom = e.rsplit("@", 1)[-1]
            if dom.endswith("users.noreply.github.com"):
                c = "noreply"
            elif dom.endswith("anthropic.com"):
                c = "vendor"
            elif PLACEHOLDER.search(dom):
                c = "placeholder"
            elif dom.endswith(HOST_SUFFIX):
                c = "host-bound"
            elif dom in PERSONAL_DOMAINS:
                c = "personal-mailbox"
            else:
                c = "other"
            cnt[(c, hashlib.sha256(e.encode()).hexdigest()[:8])] += 1
    md_table(["category", "digest8", "author+committer fields"], [(c, h, n) for (c, h), n in sorted(cnt.items(), key=lambda x: (x[0][0], -x[1]))])
    commits = {}
    for l in git("log", rev, "--format=%H\t%ae\t%ce").splitlines():
        h, a, c = l.split("\t")
        for e in (a, c):
            dom = e.lower().rsplit("@", 1)[-1]
            if dom in PERSONAL_DOMAINS:
                commits[h] = 1
    refs = [r for r in ("origin/main", "development/main") if git("rev-parse", "--verify", "-q", r, check=False).strip()]
    print(f"Commits with a personal-mailbox author or committer address: {len(commits)}; of those reachable from "
          + ", ".join(f"{r}: {sum(1 for h in commits if subprocess.run(['git','merge-base','--is-ancestor',h,r], cwd=TOP).returncode == 0)}" for r in refs) + ".\n")


SCANS = [
    ("email, non-placeholder", re.compile(rb"[A-Za-z0-9._%+-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)")),
    ("machine path /home/<user>/", re.compile(rb"/home/[a-z][a-z0-9_-]{1,31}/")),
    ("operator machine hostname suffix", re.compile(b"hst" + b"gr" + rb"\.cloud")),
    ("private key block", re.compile(rb"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----")),
    ("API token shape (sk-, ghp_, github_pat_, AKIA)", re.compile(rb"\b(?:sk-[A-Za-z0-9_-]{20,}|ghp_[A-Za-z0-9_]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16})\b")),
    ("third-party licence marker in code", re.compile(rb"(?:SPDX-License-Identifier|Licensed under the Apache|GNU General Public License|Copyright \(c\) \d{4}|Copyright \xc2\xa9 \d{4})")),
]


def section7(rev, tipset):
    print("## 7. History: blob scan\n")
    print(f"Command: `git rev-list --objects {rev}`; every distinct blob up to 30 MB is read once with `git cat-file --batch` and matched against the patterns "
          "below. Counts are blobs, not occurrences; a path is listed only with its tip status (values are never printed). "
          "Third-party e-mail domains in bibliographic text are counted as `email, non-placeholder` after removing placeholder and platform domains.\n")
    objs = [l.split(" ", 1) for l in git("rev-list", "--objects", rev).splitlines() if " " in l]
    size_ok = {}
    for l in git("cat-file", "--batch-check=%(objectname) %(objecttype) %(objectsize)", inp="\n".join(s for s, _ in objs) + "\n").splitlines():
        s, t, z = l.split()
        if t == "blob":
            size_ok[s] = int(z)
    paths = collections.defaultdict(set)
    for s, p in objs:
        if s in size_ok:
            paths[s].add(p)
    total_bytes = sum(size_ok.values())
    print(f"Distinct blobs in history: {len(size_ok)}; total uncompressed bytes {total_bytes}.\n")
    hits = collections.defaultdict(lambda: collections.defaultdict(set))
    plain_dom = re.compile(r"(example\.(com|org|net|invalid)|\.invalid$|noreply\.github\.com$|^github\.com$|anthropic\.com$|^b\.c$)")
    todo = [s for s, z in size_ok.items() if z <= 30_000_000]
    for sha, data in cat_blobs(todo):
        if b"\0" in data[:4096]:
            # binary: only the key-block and token scans are meaningful
            scans = SCANS[3:5]
        else:
            scans = SCANS
        for name, rx in scans:
            if name.startswith("email"):
                ok = False
                for m in rx.finditer(data):
                    d = m.group(1).decode("ascii", "replace").lower()
                    if not plain_dom.search(d):
                        ok = True
                        break
                if ok:
                    hits[name][sha] = paths[sha]
            elif rx.search(data):
                hits[name][sha] = paths[sha]
    tip_sha = {s for p, s, _ in tip_entries(rev)}
    for name, _ in SCANS:
        hs = hits.get(name, {})
        allp = set().union(*hs.values()) if hs else set()
        hist_only = {s: ps for s, ps in hs.items() if s not in tip_sha}
        print(f"### {name}\n")
        print(f"blobs matching: {len(hs)}; of which the tip blob of some path: {len(hs) - len(hist_only)}; history-only blobs (not at the tip): {len(hist_only)}; "
              f"distinct paths: {len(allp)}.\n")
        fc = collections.Counter(family(p) for p in allp)
        if fc:
            md_table(["family (all matching paths)", "paths"], sorted(fc.items(), key=lambda x: (-x[1], x[0]))[:12])
        if hist_only and (name.startswith(("email", "private key", "API token", "third-party licence")) or len(hist_only) <= 25):
            rows = []
            for s, ps in sorted(hist_only.items(), key=lambda x: sorted(x[1])[0]):
                fc_ = git("log", rev, "--format=%h %cs", "--diff-filter=AM", "--find-object=" + s).splitlines()
                intro = fc_[-1] if fc_ else "?"
                last = fc_[0] if fc_ else "?"
                rows.append((sorted(ps)[0], s[:10], intro, last))
            md_table(["path of history-only blob", "blob", "introduced (commit date)", "latest commit with this blob"], rows[:40])
        if name.startswith(("private key", "API token")):
            for p in sorted(allp)[:20]:
                print(f"- {p} ({'tip' if p in tipset else 'history only'})")
            print()


def section8(rev, tipset):
    print("## 8. History: historical versions of quoted-text families\n")
    print("Command: all blobs ever at paths under `fulltext_dossiers/` and `page_adjudications/` (`.md`), same quoted-run heuristic as section 3; "
          "`tip` = the version at the tip.\n")
    objs = [l.split(" ", 1) for l in git("rev-list", "--objects", rev).splitlines() if " " in l]
    sel = collections.defaultdict(set)
    for s, p in objs:
        if p.endswith(".md") and ("/fulltext_dossiers/" in p or "/page_adjudications/" in p):
            sel[s].add(p)
    tip_sha = {p: s for p, s, _ in tip_entries(rev)}
    tip_blobs = {s for s in sel if any(tip_sha.get(p) == s for p in sel[s])}
    rows = []
    for label, pick in (("all versions ever", set(sel)), ("tip versions", tip_blobs), ("versions not at tip", set(sel) - tip_blobs)):
        runs_all = []
        for sha, data in cat_blobs(sorted(pick)):
            runs, _ = quote_stats(data.decode("utf-8", "replace"))
            runs_all += runs
        rows.append((label, len(pick), len(runs_all), sum(1 for w in runs_all if w >= 25), sum(1 for w in runs_all if w >= 50), max(runs_all) if runs_all else 0, sum(runs_all)))
    md_table(["set of blobs", "blobs", "runs >=10 words", ">=25", ">=50", "longest", "words in runs"], rows)


def section0(rev):
    print("# Licence inventory output (generated)\n")
    print(f"- revision: `{git('rev-parse', rev).strip()}`; commits reachable: {git('rev-list', '--count', rev).strip()}")
    print(f"- LICENSE first line: `{git('show', rev + ':LICENSE').splitlines()[0]}`; sha256 of LICENSE blob content: "
          f"`{hashlib.sha256(git('cat-file', 'blob', rev + ':LICENSE', text=False)).hexdigest()[:16]}`")
    refs = [l for l in git("for-each-ref", "--format=%(refname:short) %(objectname:short)", "refs/remotes", "refs/heads/backup", "refs/codex").splitlines()]
    print("- non-task refs present locally (names vary with local state; not part of the reproducible counts): "
          + "; ".join(sorted(f"{r.split()[0].split('/captures/')[0]}" for r in refs)))
    for r in ("origin/main", "development/main"):
        if git("rev-parse", "--verify", "-q", r, check=False).strip():
            behind = git("rev-list", "--count", f"{r}..{rev}").strip()
            print(f"- commits of {rev} not in `{r}` (local remote-tracking ref, may be stale): {behind}")
    print()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rev", default="HEAD", help="revision to inventory; history = commits reachable from it (default HEAD)")
    ap.add_argument("--skip-blob-scan", action="store_true", help="skip sections 7 and 8 (they read every historical blob, about 2 GB)")
    a = ap.parse_args()
    rev = a.rev
    section0(rev)
    entries = tip_entries(rev)
    tipset = {p for p, _, _ in entries}
    section1(rev, entries)
    pol = section2(rev)
    section2b(rev, entries, pol)
    section3(rev, entries)
    section4(rev)
    section5(rev, pol)
    section6(rev)
    if not a.skip_blob_scan:
        section7(rev, tipset)
        section8(rev, tipset)


if __name__ == "__main__":
    main()
